def get_paper_guide(node):
    """Recognize a canonical title exactly; other papers receive a generic outline."""
    title = re.sub(r'\s+', ' ', str(node.get('label', ''))).strip().casefold()
    return deepcopy(TRANSFORMER_READING if title == 'attention is all you need' else PAPER_READING)
